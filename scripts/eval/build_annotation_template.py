"""Builds data/eval/annotation_template.csv from Condition A ablation output.

Per the approved plan (~/.claude/plans/dapper-stargazing-adleman.md, item A1),
this pre-populates rows from Condition A's findings ONLY -- system_verdict is
shown so a human annotator can see what the system concluded, but per the
plan's two-pass fix, the recommended workflow is:
  1. An annotator first writes an independent judgment for each conflict
     BLIND (reading the film's scene pairs without this file open), OR at
     minimum is aware the system_verdict column primes agreement and should
     be double-checked against the actual screenplay text, not rubber-stamped.
  2. GOLD_LABEL / GOLD_NOTES are filled in BY A HUMAN, never by an LLM --
     per the original spec's own explicit constraint, restated here.

False-negative rows (conflicts the system missed entirely) are NOT
auto-generated by this script -- that requires a human to read the source
screenplay and notice what the system didn't flag, which is exactly the kind
of judgment this script cannot perform. Add those rows manually with
system_verdict=missed, GOLD_LABEL=false_negative once identified.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ABLATION_DIR = REPO_ROOT / "data" / "eval" / "ablation"
OUT_PATH = REPO_ROOT / "data" / "eval" / "annotation_template.csv"

COLUMNS = [
    "film_slug", "conflict_id", "entity_name", "attribute", "prior_scene",
    "current_scene", "prior_excerpt", "current_excerpt", "system_verdict",
    "system_confidence", "GOLD_LABEL", "GOLD_NOTES",
]


def _rows_from_condition_a(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    film_slug = data["film"]
    rows = []
    for f in data.get("findings", []):
        rows.append({
            "film_slug": film_slug,
            "conflict_id": f.get("conflict_id", ""),
            "entity_name": f.get("entity_id", ""),  # entity_id, not a resolved display name -- see NOTE below
            "attribute": f.get("attribute", ""),
            "prior_scene": f.get("prior_evidence_unit_id", ""),
            "current_scene": f.get("current_evidence_unit_id", ""),
            "prior_excerpt": f.get("prior_evidence_excerpt", ""),
            "current_excerpt": f.get("current_evidence_excerpt", ""),
            "system_verdict": f.get("status", ""),
            "system_confidence": f.get("confidence", ""),
            "GOLD_LABEL": "",
            "GOLD_NOTES": "",
        })
    return rows


def main() -> None:
    condition_a_files = sorted(ABLATION_DIR.glob("*_condition_A.json"))
    if not condition_a_files:
        print(f"No *_condition_A.json files found in {ABLATION_DIR} -- run scripts/eval/run_ablation.py first.", file=sys.stderr)
        sys.exit(1)

    all_rows: list[dict] = []
    films = set()
    for path in condition_a_files:
        rows = _rows_from_condition_a(path)
        all_rows.extend(rows)
        if rows:
            films.add(rows[0]["film_slug"])

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_PATH, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(all_rows)

    print(f"{len(all_rows)} rows pre-populated across {len(films)} films, ready for annotation -> {OUT_PATH}")
    print(
        "NOTE: entity_name column currently holds entity_id (the resolved "
        "internal key), not a display name -- resolve against the entities "
        "table or golden_dataset conventions before annotating if a "
        "human-readable name is needed. NOTE: no false_negative rows are "
        "included yet -- add those manually per the docstring above."
    )


if __name__ == "__main__":
    main()
